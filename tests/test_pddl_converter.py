"""PDDL problem generation from the campus topology."""

from __future__ import annotations

import importlib.util
import json
import re
import sys
from pathlib import Path

import pytest

from visionleader import paths
from visionleader.navigation.hierarchical_pddl_converter import HierarchicalPDDLConverter

G, CD = 1, 2


def _load_benchmark():
    """Import experiments/planner/evaluate_planner.py, which defines the 12 problems."""
    path = paths.REPO_ROOT / "experiments" / "planner" / "evaluate_planner.py"
    spec = importlib.util.spec_from_file_location("evaluate_planner", path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


BENCHMARK = _load_benchmark()
INTRA_BUILDING = [
    p
    for p in BENCHMARK.problems
    if p.converterArgs.get("dest_building", p.converterArgs["origin_building"])
    == p.converterArgs["origin_building"]
]


def _section(problem: str, name: str) -> str:
    match = re.search(rf"\(:{name}(.*?)\n  \)", problem, re.DOTALL)
    assert match, f"no :{name} section"
    return match.group(1)


@pytest.mark.parametrize("problem", INTRA_BUILDING, ids=lambda p: p.key)
def test_generation_matches_the_frozen_benchmark(problem) -> None:
    """Intra-building problems are still generated byte for byte as benchmarked.

    The cross-building ones are expected to differ: the outdoor graph now
    links every entrance pair (see experiments/planner/README.md).
    """
    committed = BENCHMARK.evalProblemsDir / f"problem_{problem.key}.pddl"
    assert BENCHMARK._generateProblemText(problem) == committed.read_text(encoding="utf-8")


def test_problem_is_well_formed(converter: HierarchicalPDDLConverter) -> None:
    text = converter.generate_building_problem(
        origin_building=G,
        origin_room="entrance_2",
        origin_floor=0,
        dest_room="classroom_g_1_4",
        dest_floor=1,
        problem_name="unit",
    )
    assert "(define (problem unit)" in text
    assert "(:domain campus-navigation)" in text
    assert "(at user entrance_2)" in _section(text, "init")
    assert "(at user classroom_g_1_4)" in _section(text, "goal")
    assert "(:metric minimize (total-cost))" in text
    assert text.count("(") == text.count(")")


def test_every_object_used_in_init_is_declared(converter: HierarchicalPDDLConverter) -> None:
    text = converter.generate_building_problem(
        origin_building=G,
        origin_room="classroom_g_0_1",
        origin_floor=0,
        dest_building=CD,
        dest_room="classroom_cd_8",
        dest_floor=2,
    )
    declared = set(re.findall(r"[\w-]+", _section(text, "objects"))) - {"-", "location", "agent"}
    used = set()
    for fact in re.findall(r"\(([^()]+)\)", _section(text, "init")):
        used.update(fact.split()[1:])
    used = {u for u in used if not u.isdigit()}
    assert used <= declared, sorted(used - declared)


def test_cross_building_route_links_both_buildings_outdoors(
    converter: HierarchicalPDDLConverter,
) -> None:
    text = converter.generate_building_problem(
        origin_building=G,
        origin_room="classroom_g_1_4",
        origin_floor=1,
        dest_building=CD,
        dest_room="classroom_cd_3",
        dest_floor=1,
    )
    init = _section(text, "init")
    assert "(outdoor_connected entrance_2_exterior entrance_cd_exterior)" in init
    assert "(outdoor_connected entrance_cd_exterior entrance_2_exterior)" in init


def test_hurry_mode_is_a_fact_not_a_different_domain(converter: HierarchicalPDDLConverter) -> None:
    kwargs = {
        "origin_building": G,
        "origin_room": "entrance_2",
        "origin_floor": 0,
        "dest_room": "classroom_g_1_4",
        "dest_floor": 1,
    }
    calm = converter.generate_building_problem(**kwargs)
    hurry = converter.generate_building_problem(hurry_mode=True, **kwargs)
    assert "(hurry_mode)" not in calm
    assert "(hurry_mode)" in _section(hurry, "init")


def test_closing_a_room_removes_its_open_fact(tmp_path: Path) -> None:
    closures = tmp_path / "closed_rooms.json"
    closures.write_text(
        json.dumps({"closed": [{"building": "G", "location_id": "elevator", "floor": 0}]}),
        encoding="utf-8",
    )
    converter = HierarchicalPDDLConverter(
        json_path=str(paths.TOPOLOGY_PATH),
        pddl_dir=str(paths.PDDL_DIR),
        closed_rooms_path=str(closures),
    )
    text = converter.generate_building_problem(
        origin_building=G,
        origin_room="entrance_2",
        origin_floor=0,
        dest_room="classroom_g_1_4",
        dest_floor=1,
    )
    assert "(open elevator_g_f0)" not in text
    assert "(open elevator_g_f1)" in text


def test_functional_goal_resolves_to_the_hosting_building(
    converter: HierarchicalPDDLConverter,
) -> None:
    text = converter.generate_building_problem(
        origin_building=G,
        origin_room="entrance_2",
        origin_floor=0,
        goal_functional="gym",
    )
    assert "(at user gym)" in _section(text, "goal")
    assert "entrance_cd_exterior" in text


def test_unknown_functional_goal_is_an_error(converter: HierarchicalPDDLConverter) -> None:
    with pytest.raises(ValueError, match="not found"):
        converter.generate_building_problem(
            origin_building=G,
            origin_room="entrance_2",
            origin_floor=0,
            goal_functional="swimming_pool",
        )


@pytest.mark.parametrize(
    ("location_id", "floor", "building", "pddl_id"),
    [
        ("elevator", 0, "G", "elevator_g_f0"),
        ("stairs", -1, "CD", "stairs_cd_fm1"),
        ("elevator_rear", 1, "CD", "elevator_rear_cd_f1"),
        ("classroom_g_1_4", 1, "G", "classroom_g_1_4"),
    ],
)
def test_location_ids_round_trip_through_pddl(
    location_id: str, floor: int, building: str, pddl_id: str
) -> None:
    assert HierarchicalPDDLConverter.location_to_pddl(location_id, floor, building) == pddl_id
    back_id, back_floor, back_building = HierarchicalPDDLConverter.pddl_to_location(pddl_id)
    assert back_id == location_id
    if pddl_id != location_id:  # unique ids carry no floor or building
        assert (back_floor, back_building) == (floor, building)


def test_domain_declares_every_action_the_agent_understands() -> None:
    domain = paths.DOMAIN_PATH.read_text(encoding="utf-8")
    actions = set(re.findall(r"\(:action\s+([\w-]+)", domain))
    assert {"walk", "use_elevator", "outdoor_walk", "verify_elevator"} <= actions
    assert {"climb_stairs_fast", "climb_stairs_accessible"} <= actions
